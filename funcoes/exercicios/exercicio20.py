def cadastro_simples():
    nome = input("Digite seu nome: ")
    idade = int(input("Digite sua idade: "))
    profissao = input("Digite o nome da sua profissao: ")
    cidade = input("Digite o nome da sua cidade: ")
    print(f"======Cadastro======\n"
          f"Nome: {nome}\n"
          f"Idade: {idade}\n"
          f"Profissao: {profissao}\n"
          f"Cidade: {cidade}\n"
          f"======Cadastro======\n")

cadastro_simples()